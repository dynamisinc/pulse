/**
 * features/controller/engine/hooks/useEngineUsage.ts
 * ---------------------------------------------------------------------------
 * The AI-generation usage READ hook (feature: engine-telemetry-tuning, story
 * 03c; ADP-041, D5 §11). STAFF world — pure hook, no UI, no COBRA. Reads
 * `GET /api/engine/usage` (story 03a) — a live-ops volume/cost view over the
 * exercise's `engine.generated` event log, distinct from `useEngineSettings`
 * (which answers "what provider is live NOW", AC1 — this hook never repeats
 * that question; see `<UsagePanel>`'s module header for how the two are kept
 * separate).
 *
 * ## No mutations, so no await-then-apply serialization apparatus
 * Unlike `useEngineSettings` (three mutating endpoints racing on one DTO),
 * this hook only ever GETs — an idempotent read with no side effect to
 * protect. So it deliberately does NOT reuse that hook's full "one request
 * outstanding at a time" queueing model; instead it keeps the ONE guard that
 * model exists to generalize in the first place: a monotonic "latest issued
 * wins on landing" sequence number, so a slow response for an OLDER window
 * selection or an OLDER manual refresh can never overwrite a NEWER one that
 * already landed. Concurrent GETs are allowed to race freely; only landing
 * order is gated. `loading` is a per-exercise IN-FLIGHT COUNT (not a single
 * flag), so it stays `true` for as long as ANY issued request is still
 * outstanding, regardless of how many are in flight at once.
 *
 * ## No auto-refresh polling (deliberate non-goal, per the story)
 * `TelemetryEvents` carries no index on `EventType`, so every read re-scans
 * the exercise's `engine.*` rows — a polling interval would compound that on
 * every tick for every open console. This hook exposes `refresh()` (manual)
 * only; `<UsagePanel>` also calls it once on every OPEN TRANSITION, mirroring
 * `<EngineSettingsPanel>`'s own staleness discipline, but nothing here ever
 * fires on a timer.
 *
 * ## The window (AC2/AC6)
 * `windowMinutes` defaults to the server's own default (60) — deliberately
 * OMITTED from the wire request in that case (`liveEngineUsageActions`'s
 * module header, fact 1: an explicit empty value is a `400`, never a
 * fall-through). Selecting a different preset re-issues a live GET with that
 * value. The window is WALL-CLOCK throughout (COR-053 staff carve-out) — see
 * `EngineUsageWindow.clock`, always `"wall-clock"`, which `<UsagePanel>`
 * labels explicitly rather than leaving a reader to guess the clock.
 *
 * ## MOCK <-> LIVE (`USE_MOCK_DATA`, `@/core/config/mockData`)
 * Mock renders a plausible, DETERMINISTIC snapshot with NO network call,
 * generated by {@link buildMockEngineUsage} for whatever window is currently
 * selected (so the window selector visibly does something even without a
 * backend — useful for UAT, which runs on the mock flag). The mock
 * deliberately exercises every state AC2/AC3/AC8 care about in one snapshot:
 * a priced model (`AzureOpenAI`/`gpt-5.4`, real per-token rates), an UNPRICED
 * model (`AzureOpenAI`/`gpt-5.4-mini`, token counts shown, every cost field
 * `null`), an UNATTRIBUTED row (empty `provider`/`model` — a thin/partly-null
 * stored payload that still cost money), a `re-roll` in the guard mix, and a
 * non-zero `unparseableEvents`. The `Fake` provider row mirrors UAT's real
 * dataset today: real call volume, ZERO tokens (by construction), priced at
 * an honest `$0` (not "unpriced").
 *
 * `refresh()` is a NO-OP under mock (mirrors `useEngineSettings.refetch()` —
 * "there is nothing to refetch") — there is no server to go stale, so
 * re-generating the snapshot on every open-transition/manual-refresh would
 * only discard whatever a test (or a future caller) deliberately injected via
 * `engineUsageStore.setForTests`. `setWindowMinutes` is the one mock path
 * that DOES regenerate — selecting a different window is an explicit user
 * action, the same "instant apply, no server to race" treatment
 * `useEngineSettings`'s mutations get, not a passive freshness ping.
 *
 * ## PER-EXERCISE SCOPE (COR-001)
 * Module-singleton store keyed by `exerciseId` — mirrors `useEngineSettings`'s
 * / `useEngineControl`'s shape (`subscribe`/`resetForTests`), so a remount
 * under a different exercise reads a distinct snapshot and no exercise's
 * usage leaks into another's.
 *
 * ## NO TELEMETRY EMITTED HERE
 * This is a read-only observability surface over an existing event log — it
 * introduces no event of its own (AC "Telemetry (XC-004)").
 */

