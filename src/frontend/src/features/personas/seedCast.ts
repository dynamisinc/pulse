/** Approximate follower floor per audience-magnitude band (SOC-054). */
const BAND_BASE: Record<AudienceBand, number> = {
  nano: 450,
  micro: 4800,
  mid: 46000,
  large: 220000,
  mega: 1500000,
}

/**
 * Fixed pre-exercise epoch (ms) that all seeded join dates precede. A constant
 * so seeding is deterministic and reproducible; it sits before the Fairhaven
 * exercise window. Not a wall-clock read.
 */
const SEED_EPOCH_MS = Date.parse('2026-06-15T12:00:00Z')
const DAY_MS = 24 * 60 * 60 * 1000

/** Small, stable, non-negative string hash (FNV-1a-ish) for deterministic jitter. */
function stableHash(input: string): number {
  let hash = 2166136261
  for (let i = 0; i < input.length; i += 1) {
    hash ^= input.charCodeAt(i)
    hash = Math.imul(hash, 16777619)
  }
  return hash >>> 0
}

/** Derives a varied-but-deterministic follower count from the band + handle. */
function deriveFollowerCount(band: AudienceBand, handle: string): number {
  const base = BAND_BASE[band]
  // Up to +40% deterministic spread so counts within a band differ believably.
  const spread = Math.floor((stableHash(handle) % 400) / 1000 * base)
  return base + spread
}

/**
 * Derives a pre-exercise join instant. Bad actors join RECENTLY (the lookalike
 * "joined this week" tell); everyone else has an established, older account.
 */
function deriveJoinedAt(template: PersonaTemplate): string {
  const isRecent = template.personaType === 'bad-actor'
  const offsetDays = isRecent
    ? 3 + (stableHash(template.handle) % 4) // 3–6 days before the epoch
    : 90 + (stableHash(template.handle) % 640) // ~3 months to ~2 years before
  return new Date(SEED_EPOCH_MS - offsetDays * DAY_MS).toISOString()
}

/**
 * Instantiates `cast` into exercise-scoped persona instances for `exerciseId`.
 * `templates` is the org library to resolve the cast's `templateIds` against
 * (defaults to the seed library). A cast member whose template is missing is
 * skipped rather than throwing — a malformed cast never blocks seeding the rest.
 */
export function seedCast(
  cast: Cast,
  exerciseId: string,
  templates: readonly PersonaTemplate[],
): StaffPersona[] {
  const byId = new Map(templates.map(t => [t.id, t]))

  return cast.templateIds.flatMap(templateId => {
    const template = byId.get(templateId)
    if (!template) return []

    const persona: StaffPersona = {
      id: personaIdForHandle(template.handle),
      exerciseId,
      templateId: template.id,
      displayName: template.displayName,
      handle: template.handle,
      kind: template.kind,
      personaType: template.personaType,
      verified: template.verified,
      avatarColor: template.avatarColor,
      initials: template.initials,
      bio: template.bio,
      ...MOCK_PROFILE_DECOR[template.handle.toLowerCase()],
      audienceBand: template.audienceBand,
      // A freshly seeded instance has NO real follow edges yet, so the
      // composed displayed count (magnitude + real edges) is just the
      // magnitude itself — see the module header's "MOCK/LIVE PARITY" note.
      followerCount: deriveFollowerCount(template.audienceBand, template.handle),
      audienceMagnitude: deriveFollowerCount(template.audienceBand, template.handle),
      followingCount: 0,
      joinedAt: deriveJoinedAt(template),
    }
    return [persona]
  })
}
